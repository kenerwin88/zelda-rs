pub(crate) fn table_byte(address: u32) -> Option<u8> {
    for &(sprite, sheet, source) in SOURCES {
        let tables = if sprite {
            [0xcff3, 0xd0d2, 0xd1b1]
        } else {
            [0xcf80, 0xd05f, 0xd13e]
        };
        for (i, table) in tables.into_iter().enumerate() {
            if address == table + sheet as u32 {
                return Some((source >> (16 - i * 8)) as u8);
            }
        }
    }
    None
}
#[cfg(test)]
mod tests {
    use super::*;
    #[test]
    fn native_graphics_asset_locations_match_all_source_pointer_table_bytes() {
        let Ok(rom) = std::fs::read(
            std::path::Path::new(env!("CARGO_MANIFEST_DIR")).join("../../saves/zelda3.sfc"),
        ) else {
            return;
        };
        for &(sprite, sheet, _) in SOURCES {
            for base in if sprite {
                [0xcff3, 0xd0d2, 0xd1b1]
            } else {
                [0xcf80, 0xd05f, 0xd13e]
            } {
                let address = base + sheet as u32;
                assert_eq!(
                    table_byte(address),
                    Some(rom[(address & 0x7fff) as usize]),
                    "{address:06x}"
                );
            }
        }
    }
}
