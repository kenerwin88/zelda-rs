pub(super) fn work(mut iteration: usize) -> Option<((u8, u8), (u16, u16))> {
    for phase in PHASES {
        for &(count, before, after) in phase.runs {
            if iteration < usize::from(count) {
                return Some(((phase.module, phase.submodule), (before, after)));
            }
            iteration -= usize::from(count);
        }
    }
    None
}
